#!/usr/bin/env bash
# One-time Vibra install on a Hostinger KVM (Ubuntu/Debian) that may already
# host other sites. Safe to re-run: it only creates what is missing and never
# edits other nginx sites, databases or Redis data.
#
#   sudo VIBRA_BRANCH=main bash setup.sh
#
set -euo pipefail

BRANCH="${VIBRA_BRANCH:-main}"
REPO="${VIBRA_REPO:-https://github.com/sahilmuhd/Vibra.git}"
APP_DIR=/srv/vibra
WEB_DOMAIN="${VIBRA_WEB_DOMAIN:-vibra.sahilmuhd.com}"
API_DOMAIN="${VIBRA_API_DOMAIN:-api.vibra.sahilmuhd.com}"
APP_PORT=8010
REDIS_DB=5   # separate Redis database number so other apps' keys never collide

say()  { printf '\n\033[1;35m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m!!  %s\033[0m\n' "$*"; }
die()  { printf '\033[1;31mXX  %s\033[0m\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "Run as root: sudo bash setup.sh"
command -v apt-get >/dev/null || die "This script supports Ubuntu/Debian only."

# --- 1. Look before touching anything ----------------------------------------
say "Checking what is already running on this server"
WEB80="$(ss -ltnpH 'sport = :80' 2>/dev/null | grep -o 'users:(("[^"]*' | head -1 | cut -d'"' -f2 || true)"
echo "port 80 is served by: ${WEB80:-nothing}"
if [ -n "$WEB80" ] && [ "$WEB80" != "nginx" ]; then
  die "Port 80 belongs to '$WEB80', not nginx (e.g. Apache/OpenLiteSpeed/a control panel).
    Stopping so your other sites are not affected. Tell Claude which web server this is;
    Vibra then needs a vhost for that server instead of deploy/nginx/vibra.conf."
fi
if ss -ltnH "sport = :$APP_PORT" | grep -q .; then
  if ! systemctl is-active --quiet vibra-api; then
    die "Port $APP_PORT is already used by something else. Change APP_PORT here and in deploy/systemd/vibra-api.service + deploy/nginx/vibra.conf."
  fi
fi

# --- 2. Packages (only the missing ones) -------------------------------------
say "Installing missing packages"
PKGS=(git python3-venv python3-dev build-essential libpq-dev postgresql redis-server certbot python3-certbot-nginx)
[ -z "$WEB80" ] && PKGS+=(nginx)
MISSING=()
for p in "${PKGS[@]}"; do dpkg -s "$p" >/dev/null 2>&1 || MISSING+=("$p"); done
if [ "${#MISSING[@]}" -gt 0 ]; then
  apt-get update -qq
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "${MISSING[@]}"
else
  echo "all present"
fi
systemctl enable --now postgresql redis-server >/dev/null
command -v nginx >/dev/null || die "nginx is not installed and port 80 is in use."

if ! redis-cli -n "$REDIS_DB" ping 2>/dev/null | grep -q PONG; then
  die "Redis did not answer PING (password-protected?). Put the full URL with password into REDIS_URL in $APP_DIR/Back-end/.env and re-run."
fi

# --- 3. App user + code ---------------------------------------------------------
say "Creating the 'vibra' system user and fetching the code ($BRANCH)"
id vibra >/dev/null 2>&1 || useradd --system --home-dir "$APP_DIR" --shell /usr/sbin/nologin vibra
if [ ! -d "$APP_DIR/.git" ]; then
  install -d -o vibra -g vibra -m 755 "$APP_DIR"
  sudo -u vibra git clone --branch "$BRANCH" "$REPO" "$APP_DIR"
else
  echo "code already at $APP_DIR (use deploy.sh to update)"
fi
chmod 755 "$APP_DIR"   # nginx (www-data) reads the frontend files

say "Python environment"
[ -x "$APP_DIR/venv/bin/python" ] || sudo -u vibra python3 -m venv "$APP_DIR/venv"
sudo -u vibra "$APP_DIR/venv/bin/pip" install -q --upgrade pip
sudo -u vibra "$APP_DIR/venv/bin/pip" install -q -r "$APP_DIR/Back-end/requirements.txt"

# --- 4. Database + settings ----------------------------------------------------
ENV_FILE="$APP_DIR/Back-end/.env"
if [ ! -f "$ENV_FILE" ]; then
  say "Creating PostgreSQL role/database 'vibra' and writing $ENV_FILE"
  if sudo -u postgres psql -tAc "SELECT 1 FROM pg_roles WHERE rolname='vibra'" | grep -q 1; then
    die "A PostgreSQL role 'vibra' already exists but there is no $ENV_FILE. Create the .env by hand with its password, then re-run."
  fi
  DB_PASS="$(python3 -c 'import secrets; print(secrets.token_urlsafe(24))')"
  SECRET="$(python3 -c 'import secrets; print(secrets.token_urlsafe(50))')"
  sudo -u postgres psql -q -c "CREATE ROLE vibra LOGIN PASSWORD '$DB_PASS'"
  sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='vibra'" | grep -q 1 \
    || sudo -u postgres createdb -O vibra vibra
  umask 077
  cat > "$ENV_FILE" <<EOF
# Vibra production settings (generated by deploy/setup.sh on $(date -u +%F))
DJANGO_SECRET_KEY=$SECRET
DEBUG=False
PRODUCTION_DOMAIN=$WEB_DOMAIN
ALLOWED_HOSTS=$API_DOMAIN,localhost,127.0.0.1
CORS_ALLOWED_ORIGINS=https://$WEB_DOMAIN
FRONTEND_URL=https://$WEB_DOMAIN
NUM_PROXIES=1

DB_NAME=vibra
DB_USER=vibra
DB_PASSWORD=$DB_PASS
DB_HOST=localhost
DB_PORT=5432

REDIS_URL=redis://127.0.0.1:6379/$REDIS_DB

# --- fill these in, then: sudo systemctl restart vibra-api ---
LIVEKIT_API_KEY=
LIVEKIT_API_SECRET=
LIVEKIT_URL=
RAZORPAY_KEY_ID=
RAZORPAY_KEY_SECRET=
RAZORPAY_WEBHOOK_SECRET=
# EMAIL_BACKEND=django.core.mail.backends.smtp.EmailBackend
# EMAIL_HOST_USER=
# EMAIL_HOST_PASSWORD=
EOF
  umask 022
  chown vibra:vibra "$ENV_FILE"
  chmod 600 "$ENV_FILE"
else
  echo "$ENV_FILE already exists -- keeping it"
fi

say "Migrating the database and collecting static files"
cd "$APP_DIR/Back-end"
sudo -u vibra "$APP_DIR/venv/bin/python" manage.py migrate --noinput
sudo -u vibra "$APP_DIR/venv/bin/python" manage.py collectstatic --noinput -v 0

# --- 5. Services ----------------------------------------------------------------
say "Installing systemd services (API, cleanup every 2 min, nightly backup)"
install -d -o postgres -g postgres -m 700 /var/backups/vibra
install -m 644 "$APP_DIR"/deploy/systemd/vibra-*.service "$APP_DIR"/deploy/systemd/vibra-*.timer /etc/systemd/system/
systemctl daemon-reload
systemctl enable --now vibra-api.service vibra-cleanup.timer vibra-backup.timer
systemctl restart vibra-api.service

# --- 6. nginx: add Vibra's site only, test before reloading ---------------------
say "Adding the Vibra nginx site"
if grep -Rqs "include /etc/nginx/sites-enabled/" /etc/nginx/nginx.conf; then
  SITE=/etc/nginx/sites-available/vibra.conf; LINK=/etc/nginx/sites-enabled/vibra.conf
else
  SITE=/etc/nginx/conf.d/vibra.conf; LINK=""
fi
sed -e "s/server_name vibra.sahilmuhd.com;/server_name $WEB_DOMAIN;/" \
    -e "s/server_name api.vibra.sahilmuhd.com;/server_name $API_DOMAIN;/" \
    "$APP_DIR/deploy/nginx/vibra.conf" > "$SITE"
[ -n "$LINK" ] && ln -sf "$SITE" "$LINK"
if ! nginx -t 2>&1; then
  [ -n "$LINK" ] && rm -f "$LINK" || rm -f "$SITE"
  die "nginx rejected the Vibra config; it was removed again and nothing was reloaded."
fi
systemctl reload nginx

# --- 7. Smoke test ---------------------------------------------------------------
say "Checking the API through nginx"
sleep 2
# The app itself (nginx overwrites X-Forwarded-Proto, so ask daphne directly).
CODE="$(curl -s -o /dev/null -w '%{http_code}' -H "Host: $API_DOMAIN" -H 'X-Forwarded-Proto: https' "http://127.0.0.1:$APP_PORT/api/rooms/" || true)"
if [ "$CODE" = "401" ]; then
  echo "API answers (401 = needs login, as expected)"
else
  warn "API returned '$CODE' (expected 401). See: journalctl -u vibra-api -n 50"
fi
# Through nginx: before HTTPS exists Django redirects http -> https, which proves the routing.
VIA="$(curl -s -o /dev/null -w '%{http_code} %{redirect_url}' -H "Host: $API_DOMAIN" http://127.0.0.1/api/rooms/ || true)"
case "$VIA" in
  "301 https://$API_DOMAIN/"*|401*) echo "nginx routes $API_DOMAIN to the API" ;;
  *) warn "nginx returned '$VIA' for $API_DOMAIN. Check: sudo nginx -T | grep -A3 $API_DOMAIN" ;;
esac

cat <<EOF

Done. Next steps (also in deploy/README.md):
  1. DNS: point A records for $WEB_DOMAIN and $API_DOMAIN to this server's IP.
  2. HTTPS, once DNS resolves:  sudo certbot --nginx -d $WEB_DOMAIN -d $API_DOMAIN
  3. Fill LIVEKIT_* (and Razorpay) in $ENV_FILE, then: sudo systemctl restart vibra-api
EOF
